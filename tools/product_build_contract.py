"""Content identity and evidence checks shared by Upload and factory export.

This module has no PlatformIO import and never builds, flashes or edits source.
Repository content identifies the candidate; successful build evidence identifies
the exact images. A product_build.json is build evidence, not hardware acceptance.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shlex
import subprocess
from pathlib import Path

from release_build_contract import (
    ReleaseBuildContractError,
    validate_compatibility_sdkconfig,
    validate_release_identity,
)


PRODUCT_ENV = "esp32s3_unified"
PRODUCT_BOARD = "sonicwave_esp32s3_n16r8"
BUILD_HEADER = "product_build_config.h"
BUILD_METADATA = "product_build.json"
BUILD_PENDING = "product_build.pending"
ASSET_NAMES = ("firmware.bin", "bootloader.bin", "partitions.bin", "ota_data_initial.bin")
SOURCE_ROOTS = ("src", "include", "lib", "boards", "partitions")
SOURCE_FILES = (
    "firmware_release.json", "platformio.ini", "CMakeLists.txt",
    "sdkconfig.defaults", "sdkconfig.esp32s3",
    "tools/release_identity_build_flags.py", "tools/release_build_contract.py",
    "tools/product_build_contract.py",
)


class ProductBuildContractError(ValueError):
    """The image cannot be proved to match the current product candidate."""


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def file_record(path: Path) -> dict:
    if not path.is_file() or path.is_symlink():
        raise ProductBuildContractError(f"missing or symlinked build file: {path}")
    return {"sha256": sha256_file(path), "bytes": path.stat().st_size}


def load_release_config(project_dir: Path) -> dict:
    try:
        result = json.loads((project_dir / "firmware_release.json").read_text(encoding="utf-8"))
        if result.get("schema") != 1 or result.get("environment") != PRODUCT_ENV:
            raise ProductBuildContractError("unsupported product schema/environment")
        if result.get("board") != PRODUCT_BOARD:
            raise ProductBuildContractError("unsupported product board")
        validate_release_identity(result["version"], "validation")
        return result
    except (OSError, KeyError, TypeError, json.JSONDecodeError, ReleaseBuildContractError) as error:
        raise ProductBuildContractError(f"invalid firmware_release.json: {error}") from error


def source_fingerprint(project_dir: Path, platformio_env: str = PRODUCT_ENV) -> dict:
    """Hash compile inputs, including untracked source, excluding docs/Git/cache.

    Build configuration pins platform/framework dependencies. The actual SDK
    configuration is checked separately; local cache paths and commit-only
    changes do not alter the source identity.
    """
    project_dir = project_dir.resolve()
    inputs = {project_dir / name for name in SOURCE_FILES}
    for name in SOURCE_ROOTS:
        root = project_dir / name
        if root.exists():
            inputs.update(
                path for path in root.rglob("*")
                if path.is_file() and path.suffix.lower() not in (".md", ".pyc", ".pyo")
                and path.name not in ("README", ".DS_Store")
                and not any(part in ("__pycache__", ".git", "build") for part in path.relative_to(root).parts)
            )
    records = {}
    for path in sorted(inputs):
        if not path.is_file() or path.is_symlink():
            raise ProductBuildContractError(f"missing or symlinked build input: {path}")
        records[path.relative_to(project_dir).as_posix()] = sha256_file(path)
    content = json.dumps({"environment": platformio_env, "files": records}, sort_keys=True, separators=(",", ":"))
    return {"source_sha256": hashlib.sha256(content.encode()).hexdigest(), "source_files": records}


def current_product_identity(project_dir: Path) -> dict:
    config = load_release_config(project_dir)
    fingerprint = source_fingerprint(project_dir, config["environment"])
    version_numbers = config["version"].removeprefix("SW-ESP32-").replace(".", "")
    return {
        "version": config["version"],
        "build_id": f"u{version_numbers}-{fingerprint['source_sha256'][:12]}",
        "platformio_env": config["environment"],
        "board": config["board"],
        "identity_mode": "product",
        **fingerprint,
    }


def render_build_header(version: str, build_id: str, backend: str, *, usb_diagnostics: bool = False,
                        fail_self_check: bool = False) -> str:
    validate_release_identity(version, build_id)
    if not version or backend not in ("UNIFIED", "485", "CYD3S1612_IIC"):
        raise ProductBuildContractError("explicit identity and a known backend are required")
    lines = ["#pragma once", "// Generated by the PlatformIO build; do not edit.",
             f'#define FW_VER "{version}"', f'#define FW_BUILD_ID "{build_id}"',
             f"#define SW_DISTANCE_BACKEND_{backend} 1"]
    if usb_diagnostics:
        lines.extend(["#define SW_ESP32_ROLLBACK_USB_DIAGNOSTICS 1", "#define ARDUINO_USB_MODE 1",
                      "#define ARDUINO_USB_CDC_ON_BOOT 1"])
    if fail_self_check:
        lines.append("#define SW_OTA_ROLLBACK_TEST_INJECT_SELF_CHECK_FAILURE 1")
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def prepare_build_header(build_dir: Path, content: str) -> None:
    # An identity/input change also invalidates CMake's cached source inventory.
    # Without reconfiguration a newly added .cpp can be omitted by GLOB_RECURSE.
    if write_if_changed(build_dir / BUILD_HEADER, content):
        (build_dir / "CMakeCache.txt").unlink(missing_ok=True)


def verify_compile_contract(project_dir: Path, build_dir: Path, identity: dict) -> dict:
    header = build_dir / BUILD_HEADER
    expected = render_build_header(identity["version"], identity["build_id"], "UNIFIED")
    if not header.is_file() or header.read_text(encoding="utf-8") != expected:
        raise ProductBuildContractError("product identity/backend header is missing or differs")
    try:
        commands = json.loads((build_dir / "compile_commands.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ProductBuildContractError(f"actual compile commands are unavailable: {error}") from error
    source_dir = (project_dir / "src").resolve()
    source_units = {path.resolve() for path in source_dir.rglob("*.cpp")}
    checked = set()
    for item in commands:
        path = Path(item["file"]).resolve()
        if path not in source_units:
            continue
        args = item.get("arguments") or shlex.split(item["command"])
        includes = []
        for index, arg in enumerate(args):
            if arg == "-include" and index + 1 < len(args):
                includes.append(args[index + 1])
            elif arg.startswith("-include"):
                includes.append(arg[len("-include"):])
        includes = {str((Path(item.get("directory", build_dir)) / value).resolve()) for value in includes}
        if str(header.resolve()) not in includes:
            raise ProductBuildContractError(f"actual component compile omitted product header: {path.name}")
        forbidden = ("-DSW_DISTANCE_BACKEND_485", "-DSW_DISTANCE_BACKEND_CYD3S1612_IIC", "-DFW_VER", "-DFW_BUILD_ID")
        if any(arg.startswith(forbidden) for arg in args):
            raise ProductBuildContractError(f"conflicting component identity/backend flags: {path.name}")
        checked.add(path)
    if not source_units or checked != source_units:
        raise ProductBuildContractError("actual compile source inventory differs from current src/*.cpp")
    return {"backend": "UNIFIED", "forced_include": BUILD_HEADER, "application_units": len(checked)}


def build_evidence(project_dir: Path, build_dir: Path, identity: dict, sdkconfig: Path) -> dict:
    current = current_product_identity(project_dir)
    if identity != current:
        raise ProductBuildContractError("build inputs changed while compiling; build again")
    if sdkconfig.resolve() != (build_dir / "sdkconfig.product").resolve():
        raise ProductBuildContractError("product build must use its generated sdkconfig.product")
    cache = (build_dir / "CMakeCache.txt").read_text(encoding="utf-8")
    selected = re.search(r"^SDKCONFIG:[^=]+=(.+)$", cache, re.MULTILINE)
    if not selected or Path(selected.group(1)).resolve() != sdkconfig.resolve():
        raise ProductBuildContractError("actual CMake SDKCONFIG differs from the product configuration")
    actual_sdkconfig = sdkconfig.read_text(encoding="utf-8")
    validate_compatibility_sdkconfig(actual_sdkconfig)
    if re.search(r"^CONFIG_APP_COMPILE_TIME_DATE=y$", actual_sdkconfig, re.MULTILINE):
        raise ProductBuildContractError("product build must not embed a varying compile date/time")
    compile_contract = verify_compile_contract(project_dir, build_dir, identity)
    firmware = (build_dir / "firmware.bin").read_bytes()
    for field in ("version", "build_id"):
        if identity[field].encode() + b"\x00" not in firmware:
            raise ProductBuildContractError(f"compiled firmware does not contain {field}={identity[field]}")
    try:
        commit = subprocess.check_output(["git", "-C", str(project_dir), "rev-parse", "HEAD"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    return {
        "schema": 1, **identity, "firmware_commit": commit,
        "assets": {name: file_record(build_dir / name) for name in ASSET_NAMES},
        "sdkconfig": {"path": str(sdkconfig.resolve()), "sha256": sha256_file(sdkconfig)},
        "compile_contract": compile_contract,
    }


def verify_product_build(project_dir: Path, build_dir: Path | None = None) -> dict:
    project_dir = Path(project_dir).resolve()
    current = current_product_identity(project_dir)
    build_dir = (Path(build_dir) if build_dir is not None else project_dir / ".pio" / "build" / PRODUCT_ENV).resolve()
    if (build_dir / BUILD_PENDING).exists():
        raise ProductBuildContractError("last product build has not completed successfully")
    try:
        metadata = json.loads((build_dir / BUILD_METADATA).read_text(encoding="utf-8"))
        if metadata.get("schema") != 1:
            raise ProductBuildContractError("unsupported product build metadata schema")
        for key, value in current.items():
            if metadata.get(key) != value:
                raise ProductBuildContractError(f"stale or non-product build: {key} differs; rebuild {PRODUCT_ENV}")
        evidence = build_evidence(project_dir, build_dir, current, Path(metadata["sdkconfig"]["path"]))
        for key in ("assets", "sdkconfig", "compile_contract"):
            if metadata.get(key) != evidence[key]:
                raise ProductBuildContractError(f"built {key} differ from recorded evidence")
        return metadata
    except (OSError, KeyError, TypeError, json.JSONDecodeError, ReleaseBuildContractError) as error:
        raise ProductBuildContractError(f"invalid product build evidence: {error}") from error


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-dir", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--build-dir", type=Path)
    parser.add_argument("--identity-only", action="store_true")
    args = parser.parse_args()
    try:
        result = current_product_identity(args.project_dir) if args.identity_only else verify_product_build(args.project_dir, args.build_dir)
        print(json.dumps(result, indent=2, ensure_ascii=False))
    except ProductBuildContractError as error:
        parser.exit(2, f"product build rejected: {error}\n")


if __name__ == "__main__":
    main()
